create table if not exists fraud_decision (
  id bigint generated by default as identity primary key,
  amount double precision not null,
  recent_transactions integer not null,
  account_age_days integer not null,
  country_mismatch boolean not null,
  risk_score integer not null,
  risk_band varchar(12) not null,
  created_at timestamp not null default current_timestamp,
  analyst_label varchar(20),
  labeled_at timestamp
);
create index if not exists ix_fraud_decision_review on fraud_decision(risk_band, analyst_label, created_at desc);
