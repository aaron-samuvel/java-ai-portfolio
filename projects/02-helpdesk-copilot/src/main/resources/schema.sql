create table if not exists helpdesk_order (
  order_id varchar(40) primary key,
  customer_id varchar(80) not null,
  status varchar(40) not null,
  delivery_date varchar(20) not null,
  return_eligible boolean not null
);
create table if not exists helpdesk_return_request (
  order_id varchar(40) primary key,
  customer_id varchar(80) not null,
  request_id varchar(40) not null unique,
  created_at timestamp not null default current_timestamp
);
create table if not exists helpdesk_ticket (
  ticket_id varchar(40) primary key,
  customer_id varchar(80) not null,
  idempotency_key varchar(64) not null,
  summary varchar(400) not null,
  status varchar(20) not null,
  created_at timestamp not null default current_timestamp,
  unique(customer_id, idempotency_key)
);
create table if not exists helpdesk_audit (
  event_id bigint generated by default as identity primary key,
  action varchar(40) not null,
  customer_id varchar(80) not null,
  subject varchar(100) not null,
  created_at timestamp not null default current_timestamp
);
